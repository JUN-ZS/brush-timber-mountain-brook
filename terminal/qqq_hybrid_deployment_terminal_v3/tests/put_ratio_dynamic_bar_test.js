import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import {fileURLToPath} from "node:url";
import "../put_ratio_dynamic_bar.js";
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,"..");
const M=globalThis.PutRatioDynamicBarV1;
const s=JSON.parse(fs.readFileSync(path.join(root,"put_ratio_dynamic_bar_v1.json"),"utf8"));
assert.ok(M,"browser/ESM global API should be initialized");
assert.equal(M.validateSnapshot(s).ok,true,JSON.stringify(M.validateSnapshot(s).reasons));
assert.equal(s.metadata.allowedUnits,0);
assert.equal(s.metadata.budgetBreachEpisodes,62);
assert.equal(s.barRows.length,162);
assert.equal(s.drawdownRows.length,14);
assert.deepEqual([...new Set(s.barRows.map(r=>r[3]))].sort((a,b)=>a-b),[0.5,1,2]);
const hold=M.policyById(s,"DTE7_CLOSE_SHORT_RISK");
const closeLong=M.policyById(s,"DTE7_CLOSE_SHORT_AND_SELL_LONG_IF_EXECUTABLE");
assert.equal(hold.episodes,62);
assert.equal(closeLong.pnl,18067.6);
assert.equal(closeLong.budgetBreaches,62);
const holdAll=M.barRowsFor(s,0,0);
const holdProfit05=holdAll.find(r=>r.barTypeIndex===0&&r.levelPct===0.5);
assert.equal(holdProfit05.episodeHits,17);
assert.equal(holdProfit05.episodeN,62);
assert.equal(holdProfit05.episodePct,27.4194);
const closeAll=M.barRowsFor(s,1,0);
const closeProfit05=closeAll.find(r=>r.barTypeIndex===0&&r.levelPct===0.5);
assert.equal(closeProfit05.episodeHits,15);
assert.equal(closeProfit05.levelPct,0.5);
assert.equal(closeAll.length,9);
const highVix=M.barRowsFor(s,1,4).find(r=>r.barTypeIndex===1&&r.levelPct===1);
assert.equal(highVix.episodeN,10);
assert.equal(highVix.episodePct,40);
assert.equal(highVix.sampleStatus,"PENDING_SMALL_EPISODE_SAMPLE");
const dd=M.drawdownRowsFor(s,1);
assert.equal(dd.find(r=>r.levelPct===3).eventYearPct,37.5);
assert.deepEqual(dd.find(r=>r.levelPct===5).eventYears,["2025"]);
const invalid=JSON.parse(JSON.stringify(s));invalid.metadata.allowedUnits=1;
assert.equal(M.validateSnapshot(invalid).ok,false,"must fail closed if budget gate changes");
console.log("Dynamic BAR snapshot PASS — source, exact 1:5, budget-bypass gate, 162 BAR slices, and DD tiers");
